/**
 * Generate pages/*_static.html — DOM snapshots after JS chrome init, without <script>.
 *
 * Usage (from SAMPLES/):
 *   node scripts/generate-static-pages.mjs
 *
 * Needs Playwright Chromium:
 *   npx playwright install chromium
 */
import fs from "node:fs";
import path from "node:path";
import http from "node:http";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const PAGES = path.join(ROOT, "pages");

const MIME = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".png": "image/png",
  ".svg": "image/svg+xml",
  ".mp4": "video/mp4",
  ".wav": "audio/wav",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
};

function startServer() {
  return new Promise((resolve) => {
    const server = http.createServer((req, res) => {
      const urlPath = decodeURIComponent((req.url || "/").split("?")[0]);
      let rel = urlPath.replace(/^\/+/, "");
      if (!rel || rel.endsWith("/")) rel += "index.html";
      const filePath = path.normalize(path.join(ROOT, rel));
      if (!filePath.startsWith(ROOT)) {
        res.writeHead(403);
        res.end("Forbidden");
        return;
      }
      fs.readFile(filePath, (err, data) => {
        if (err) {
          res.writeHead(404);
          res.end("Not found");
          return;
        }
        const ext = path.extname(filePath).toLowerCase();
        res.writeHead(200, { "Content-Type": MIME[ext] || "application/octet-stream" });
        res.end(data);
      });
    });
    server.listen(0, "127.0.0.1", () => {
      const { port } = server.address();
      resolve({ server, port });
    });
  });
}

function listSourcePages() {
  return fs
    .readdirSync(PAGES)
    .filter((f) => f.endsWith(".html") && !f.includes("_static"))
    .sort();
}

async function snapshotPage(browser, baseUrl, file) {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const url = `${baseUrl}/pages/${encodeURIComponent(file)}`;
  await page.goto(url, { waitUntil: "domcontentloaded", timeout: 60000 });

  // Wait for shared chrome fill (main toolbar buttons), or catalog cards.
  await page
    .waitForFunction(() => {
      const tb = document.querySelector('[data-chrome="main-toolbar"]');
      if (tb && tb.childElementCount > 0) return true;
      return !!document.querySelector("#ui-catalog-root .ui-catalog-card, #ui-catalog-root .ui-catalog-welcome");
    }, { timeout: 20000 })
    .catch(() => {});

  // Extra settle for dialogs / event upgrades / CF zones / catalog build.
  await page.waitForTimeout(600);

  const html = await page.evaluate((sourceName) => {
    document.querySelectorAll("script").forEach((s) => s.remove());
    document.documentElement.setAttribute("data-static", "1");
    document.body.classList.add("is-static-page");

    // Soften pointer cursor hints that imply interactivity.
    const note = document.createElement("meta");
    note.name = "generator";
    note.content = `static-snapshot:${sourceName}`;
    document.head.appendChild(note);

    const doctype = "<!DOCTYPE html>\n";
    const banner =
      "<!--\n" +
      "  Static snapshot of " +
      sourceName +
      " — HTML/CSS only (no JS).\n" +
      "  Regenerated by: node scripts/generate-static-pages.mjs\n" +
      "-->\n";
    return banner + doctype + document.documentElement.outerHTML;
  }, file);

  await page.close();

  const outName = file.replace(/\.html$/i, "_static.html");
  const outPath = path.join(PAGES, outName);
  fs.writeFileSync(outPath, html, "utf8");
  return outName;
}

async function main() {
  const sources = listSourcePages();
  if (!sources.length) {
    console.error("No source pages found in", PAGES);
    process.exit(1);
  }

  const { server, port } = await startServer();
  const baseUrl = `http://127.0.0.1:${port}`;
  console.log("Serving", ROOT, "at", baseUrl);

  const browser = await chromium.launch({ headless: true });
  const written = [];
  try {
    for (const file of sources) {
      process.stdout.write(`  ${file} → `);
      const out = await snapshotPage(browser, baseUrl, file);
      console.log(out);
      written.push(out);
    }
  } finally {
    await browser.close();
    server.close();
  }

  console.log(`Done: ${written.length} static page(s).`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
