#pragma once

#include <QString>
#include <QVariantMap>
#include <QVector>

namespace openvegas {

/** One stock Media Generator preset: its name and the values VEGAS stores for it. */
struct StockGeneratorPreset {
    QString name;
    /**
     * VEGAS's own parameter names and shapes — a colour is [r, g, b, a] in 0..1, a choice
     * or boolean a number — the same map the importer reads out of a project. Empty for
     * the legacy generators, whose stored parameters are not decoded.
     */
    QVariantMap params;
};

/** All stock presets of one generator, in the order VEGAS's browser lists them. */
struct StockGeneratorGroup {
    /** "{Svfx:…}" for an OFX generator, the CLSID in braces for a legacy one. */
    QString pluginId;
    /** The browser's name for it, e.g. "Noise Texture". */
    QString name;
    QVector<StockGeneratorPreset> presets;
};

/**
 * Every non-text Media Generator VEGAS 22 ships, with its stock presets.
 *
 * Generated by tools/gen_generator_presets.py from VEGAS's PresetPackage.xml (the four
 * OFX generators) and sftrans1.dll's string table (Color Gradient and Credit Roll).
 */
const QVector<StockGeneratorGroup> &stockGeneratorPresets();

/** The group for a VEGAS generator id, case-insensitively; nullptr when unknown. */
const StockGeneratorGroup *stockGeneratorGroup(const QString &pluginId);

/** One stock preset by generator id and preset name; nullptr when there is none. */
const StockGeneratorPreset *stockGeneratorPreset(const QString &pluginId, const QString &presetName);

} // namespace openvegas
