#!/usr/bin/env python3
"""Generate the Titles & Text stock preset table from what VEGAS itself ships.

VEGAS's Titles & Text presets are plain XML in

    OFX Video Plug-Ins/TitlesAndText.ofx.bundle/Contents/Presets/PresetPackage.xml

Each holds the text as RTF and every parameter the plug-in has: colours, scale, location,
anchor ("Alignment"), tracking, line spacing, outline and shadow. Values keep VEGAS's own
units, which are what the importer reads out of a project (parseVideoTitlesText()), so a
preset placed from the browser and the same preset opened from a .veg carry the same data.
Location's Y counts up from the bottom of the frame, as VEGAS's does.

The RTF is reduced the way the importer reduces it: the first font, the first size (in
half-points, so halved), bold and italic when set, the paragraph alignment, and the plain
text with one line per paragraph.

Two things the package does not hold:

* "(Default)", which VEGAS lists first and captions "Sample Text": the plug-in's own
  defaults, which are TitlesTextParams's.
* Rough Day's text colour, stored fully transparent; VEGAS's browser draws that preset's
  text black, and so does the table.

Run from the repo root:

    python tools/gen_titles_presets.py > src/video/TitlesTextPresetData.cpp
"""

import re
import sys
import xml.etree.ElementTree as ET

XML = ("SAMPLES/VEGAS-PRO-22-PROGRAM-FILES/OFX Video Plug-Ins/TitlesAndText.ofx.bundle/"
       "Contents/Presets/PresetPackage.xml")

ALIGN = {"ql": 0, "qc": 1, "qr": 2}


def strip_group(rtf, name):
    start = rtf.find("{\\" + name)
    if start < 0:
        return rtf
    depth = 0
    for i in range(start, len(rtf)):
        if rtf[i] == "{":
            depth += 1
        elif rtf[i] == "}":
            depth -= 1
            if depth == 0:
                return rtf[:start] + rtf[i + 1:]
    return rtf[:start]


def parse_rtf(rtf):
    font = re.search(r"\\fcharset\d+\s+([^;]+);", rtf)
    size = re.search(r"\\fs(\d+)", rtf)
    align = re.search(r"\\(q[lcr])(?![a-z])", rtf)
    out = {
        "font": font.group(1).strip() if font else "Verdana",
        "size": int(size.group(1)) / 2.0 if size else 48.0,
        "bold": re.search(r"\\b(?![a-z0-9])", rtf) is not None,
        "italic": re.search(r"\\i(?![a-z0-9])", rtf) is not None,
        "align": ALIGN[align.group(1)] if align else 0,
    }
    # Line breaks in RTF source are not text, paragraphs are; one right after a control word
    # ends that word, as a space would.
    body = strip_group(strip_group(rtf, "fonttbl"), "colortbl")
    body = re.sub(r"(\\[a-z]+-?\d*)\r?\n", r"\1 ", body).replace("\r", "").replace("\n", "")
    body = re.sub(r"\\par(?![a-z]) ?", "\n", body)
    body = re.sub(r"\\'([0-9a-fA-F]{2})", lambda m: bytes([int(m.group(1), 16)]).decode("cp1252"),
                  body)
    body = re.sub(r"\\[a-z]+-?\d* ?", "", body)
    body = body.replace("{", "").replace("}", "")
    out["text"] = body.strip()
    return out


def floats(text):
    return [float(v) for v in text.split()]


def cpp_string(s):
    return "QStringLiteral(\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace(
        "\n", "\\n") + "\")"


def num(x):
    return repr(round(x, 6))


def colour(rgba):
    return "QColor::fromRgbF(%s)" % ", ".join(num(v) for v in rgba)


def main():
    root = ET.parse(XML).getroot()
    out = sys.stdout
    out.write("// Generated by tools/gen_titles_presets.py - do not edit by hand.\n")
    out.write("//\n")
    out.write("// Source: VEGAS's own PresetPackage.xml inside the TitlesAndText OFX bundle.\n\n")
    out.write("#include \"video/TitlesTextApply.h\"\n\n")
    out.write("namespace openvegas {\n\n")
    out.write("const QVector<TitlesTextStockPreset> &titlesTextStockPresets()\n{\n")
    out.write("    static const QVector<TitlesTextStockPreset> presets = [] {\n")
    out.write("        QVector<TitlesTextStockPreset> t;\n")
    out.write("        t.push_back({QStringLiteral(\"(Default)\"), TitlesTextParams{}});\n")
    for preset in root.iter("OfxPreset"):
        v = {e.get("name"): (e.find("OfxParamValue").text or "").strip()
             for e in preset if e.get("name")}
        r = parse_rtf(v["Text"])
        text_colour = floats(v["TextColor"])
        if text_colour[3] == 0.0:
            text_colour = [0.0, 0.0, 0.0, 1.0]
        loc = floats(v["Location"])
        fields = [
            ("text", cpp_string(r["text"])),
            ("fontFamily", cpp_string(r["font"])),
            ("fontSize", num(r["size"])),
            ("bold", "true" if r["bold"] else "false"),
            ("italic", "true" if r["italic"] else "false"),
            ("alignment", "static_cast<TitlesTextAlignment>(%d)" % r["align"]),
            ("textColor", colour(text_colour)),
            ("animationName", cpp_string(v["AnimationName"])),
            ("scale", num(float(v["Scale"]))),
            ("locationX", num(loc[0])),
            ("locationY", num(loc[1])),
            ("anchor", "static_cast<TitlesTextAnchor>(%d)" % int(v.get("Alignment", "4"))),
            ("backgroundColor", colour(floats(v["Background"]))),
            ("tracking", num(float(v["Tracking"]))),
            ("lineSpacing", num(float(v["LineSpacing"]))),
            ("outlineWidth", num(float(v["OutlineWidth"]))),
            ("outlineColor", colour(floats(v["OutlineColor"]))),
            ("shadowEnable", "true" if v["ShadowEnable"] == "true" else "false"),
            ("shadowColor", colour(floats(v["ShadowColor"]))),
            ("shadowOffsetX", num(float(v["ShadowOffsetX"]))),
            ("shadowOffsetY", num(float(v["ShadowOffsetY"]))),
            ("shadowBlur", num(float(v["ShadowBlur"]))),
        ]
        out.write("        {\n")
        out.write("            TitlesTextParams p;\n")
        for name, value in fields:
            out.write("            p.%s = %s;\n" % (name, value))
        out.write("            t.push_back({%s, p});\n" % cpp_string(preset.get("name")))
        out.write("        }\n")
    out.write("        return t;\n")
    out.write("    }();\n")
    out.write("    return presets;\n")
    out.write("}\n\n")
    out.write("} // namespace openvegas\n")


if __name__ == "__main__":
    main()
